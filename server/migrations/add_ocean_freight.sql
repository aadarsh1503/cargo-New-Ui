CREATE TABLE IF NOT EXISTS ocean_freight (
  id INT AUTO_INCREMENT PRIMARY KEY,
  agent_id INT NOT NULL,
  liner VARCHAR(255) NOT NULL,
  pol VARCHAR(255) NOT NULL,
  pod VARCHAR(255) NOT NULL,
  transit_time VARCHAR(50),
  availability VARCHAR(100),
  price_20gp DECIMAL(10,2) DEFAULT NULL,
  price_40gp DECIMAL(10,2) DEFAULT NULL,
  price_40hq DECIMAL(10,2) DEFAULT NULL,
  price_40nor DECIMAL(10,2) DEFAULT NULL,
  price_45hq DECIMAL(10,2) DEFAULT NULL,
  currency VARCHAR(10) DEFAULT 'USD',
  remarks TEXT,
  is_active BOOLEAN DEFAULT TRUE,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  FOREIGN KEY (agent_id) REFERENCES agents(id) ON DELETE CASCADE,
  INDEX idx_agent_id (agent_id),
  INDEX idx_pol_pod (pol, pod)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
